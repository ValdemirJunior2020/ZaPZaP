-- Apply ONLY to a dedicated NexusSales Supabase project, after nexussales-trial-paypal.sql.
-- Owner contact profile. Email is owned by Supabase Auth; do not permit users to assign privileges.
create table if not exists public.nx_owner_profiles (
  owner_id uuid primary key references auth.users(id) on delete cascade,
  business_name text not null check (char_length(business_name) between 2 and 150),
  phone text not null check (char_length(phone) between 7 and 30),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.nx_owner_profiles enable row level security;
revoke all on public.nx_owner_profiles from anon,authenticated;
grant select,update on public.nx_owner_profiles to authenticated;
create policy "owner reads own business profile" on public.nx_owner_profiles
 for select to authenticated using (owner_id=(select auth.uid()));
create policy "owner updates own business profile" on public.nx_owner_profiles
 for update to authenticated using (owner_id=(select auth.uid()))
 with check(owner_id=(select auth.uid()));

-- Signup metadata is business contact data only; NEVER use it to authorize
-- super admin, roles, payments or trial duration.
create or replace function nx_private.create_owner_profile()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare name text; tel text;
begin
  name:=left(trim(coalesce(new.raw_user_meta_data->>'business_name','')),150);
  tel:=left(trim(coalesce(new.raw_user_meta_data->>'phone','')),30);
  if length(name) between 2 and 150 and length(tel) between 7 and 30 then
    insert into public.nx_owner_profiles(owner_id,business_name,phone,created_at)
    values(new.id,name,tel,new.created_at)
    on conflict (owner_id) do nothing;
  end if;
  return new;
end;
$$;
revoke all on function nx_private.create_owner_profile() from public,anon,authenticated;
drop trigger if exists nx_create_profile_after_signup on auth.users;
create trigger nx_create_profile_after_signup
 after insert on auth.users for each row execute function nx_private.create_owner_profile();
